import { cp, mkdir, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'node_modules/@mdi/svg/svg');
const publicDir = join(root, 'public/mdi-icons');
const registryFile = join(root, 'src/lib/state/icon-registry.generated.ts');

if (!existsSync(sourceDir)) throw new Error('@mdi/svg fehlt; zuerst npm install ausführen.');

const names = (await readdir(sourceDir))
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .sort();

const categoryPatterns = {
  light: /lightbulb|lamp|light|led|candle|chandelier|sun|moon|brightness/,
  switch: /switch|plug|outlet|power|bolt|fan|blinds|window|door|garage|lock|key|cover|lightning/,
  climate: /thermometer|temperature|fire|snowflake|water|humidity|wind|cloud|weather|gauge|radiator|leaf/,
  media: /play|pause|volume|speaker|headphone|microphone|radio|television|tv\b|movie|video|camera|cast|music/,
  system: /home|settings|cog|menu|arrow|chevron|search|account|wifi|router|network|server|database|shield|bell|calendar|clock|navigation|map|location|info\b|alert|check|plus|minus/,
};

function categoriesFor(name) {
  const categories = Object.entries(categoryPatterns)
    .filter(([, pattern]) => pattern.test(name))
    .map(([category]) => category);
  return categories.length ? categories : ['all'];
}

const rows = names.map((name) => ({ id: `i-${name}`, name, asset: name, categories: categoriesFor(name) }));
rows.sort((a, b) => a.id.localeCompare(b.id));

const output = `/* AUTO-GENERATED by scripts/generate-icon-registry.mjs — do not edit. */\n` +
  `export interface GeneratedIcon { id: string; name: string; asset: string; categories: readonly string[] }\n` +
  `export const GENERATED_ICON_REGISTRY: readonly GeneratedIcon[] = ${JSON.stringify(rows)};\n`;
await writeFile(registryFile, output);
console.log(`MDI Registry: ${rows.length} IDs -> ${registryFile}`);

if (process.argv.includes('--copy-assets')) {
  await mkdir(publicDir, { recursive: true });
  await cp(sourceDir, publicDir, { recursive: true, force: true });
  console.log(`MDI Assets: ${names.length} SVGs -> ${publicDir}`);
}
